import {
  SkyviewError,
  SkyviewParseError,
  SkyviewRateLimitError,
  SkyviewRequestError,
  SkyviewTimeoutError,
} from './errors';
import type {
  SkyviewClientConfig,
  SkyviewCutoutOptions,
  SkyviewPosition,
  SkyviewSurvey,
} from './types';

export const DEFAULT_SKYVIEW_BASE_URL = 'https://skyview.gsfc.nasa.gov';
const DEFAULT_TIMEOUT_MS = 30_000;

/**
 * Formats a `SkyviewPosition` into a SkyView-compatible coordinate string.
 */
export function formatSkyviewPosition(pos: SkyviewPosition): string {
  if (typeof pos === 'string') {
    return pos.trim();
  }
  return `${pos.ra.toFixed(6)}, ${pos.dec.toFixed(6)}`;
}

/**
 * Client for NASA Goddard Space Flight Center's SkyView Image Service.
 *
 * SkyView generates high-quality optical, infrared, and ultraviolet cutouts
 * from 100+ space telescope and ground-based astronomical surveys (2MASS, WISE, DSS, GALEX).
 *
 * All imagery generated by NASA SkyView is in the **United States Public Domain**
 * (17 U.S.C. § 105) and may be freely published, displayed, or used in commercial fine-art prints.
 */
export class SkyviewClient {
  private readonly baseUrl: string;
  private readonly defaultTimeoutMs: number;
  private readonly fetchFn: typeof fetch;

  constructor(config: SkyviewClientConfig = {}) {
    this.baseUrl = (config.baseUrl ?? DEFAULT_SKYVIEW_BASE_URL).replace(/\/+$/, '');
    this.defaultTimeoutMs = config.timeoutMs ?? DEFAULT_TIMEOUT_MS;
    this.fetchFn = config.fetch ?? fetch;
  }

  /**
   * Generates a direct image cutout URL for NASA SkyView.
   * Can be used directly in `<img src="...">`, CSS backgrounds, or HTML5 Canvas `drawImage`.
   *
   * @param options Cutout parameters (coordinates, survey, field of view, pixel size)
   * @param format Image format ('jpg', 'png', or 'fits'). Defaults to 'jpg'.
   */
  getImageUrl(
    options: SkyviewCutoutOptions,
    format: 'jpg' | 'png' | 'fits' = 'jpg'
  ): string {
    const params = new URLSearchParams();

    params.set('Position', formatSkyviewPosition(options.position));

    const surveyStr = Array.isArray(options.survey)
      ? options.survey.join(',')
      : (options.survey ?? 'DSS2 Color');
    params.set('Survey', surveyStr);

    if (options.pixels) {
      params.set('Pixels', String(options.pixels));
    }
    if (options.sizeDeg != null) {
      params.set('Size', String(options.sizeDeg));
    }
    if (options.projection) {
      params.set('Projection', options.projection);
    }
    if (options.scaling) {
      params.set('Scaling', options.scaling);
    }
    if (options.lut) {
      params.set('lut', options.lut);
    }
    if (options.coordinates) {
      params.set('Coordinates', options.coordinates);
    }

    const returnFormat =
      format === 'fits' ? 'FITS' : format === 'png' ? 'PNG' : 'JPEG';
    params.set('Return', returnFormat);

    return `${this.baseUrl}/current/cgi/runquery.pl?${params.toString()}`;
  }

  /**
   * Fetches the image cutout as a browser/Node `Blob`.
   */
  async fetchImageBlob(
    options: SkyviewCutoutOptions,
    format: 'jpg' | 'png' = 'jpg'
  ): Promise<Blob> {
    const url = this.getImageUrl(options, format);
    const response = await this.executeRequest(url, options.timeoutMs);
    return await response.blob();
  }

  /**
   * Fetches the image cutout as an `ArrayBuffer`.
   */
  async fetchImageArrayBuffer(
    options: SkyviewCutoutOptions,
    format: 'jpg' | 'png' = 'jpg'
  ): Promise<ArrayBuffer> {
    const url = this.getImageUrl(options, format);
    const response = await this.executeRequest(url, options.timeoutMs);
    return await response.arrayBuffer();
  }

  /**
   * Fetches a raw astronomical FITS file cutout.
   */
  async fetchFits(options: SkyviewCutoutOptions): Promise<ArrayBuffer> {
    const url = this.getImageUrl(options, 'fits');
    const response = await this.executeRequest(url, options.timeoutMs);
    return await response.arrayBuffer();
  }

  /**
   * Returns the official public domain attribution and credit line
   * suitable for publication, art prints, or web apps.
   */
  getAttribution(survey?: SkyviewSurvey): string {
    const surveyName = survey ? String(survey) : 'NASA SkyView';
    if (surveyName.includes('2MASS')) {
      return 'Image courtesy of NASA / IPAC / 2MASS (U.S. Public Domain).';
    }
    if (surveyName.includes('WISE')) {
      return 'Image courtesy of NASA / JPL-Caltech / WISE (U.S. Public Domain).';
    }
    return `NASA SkyView (${surveyName}) image courtesy of NASA/GSFC. U.S. Public Domain.`;
  }

  private async executeRequest(url: string, timeoutMs?: number): Promise<Response> {
    const timeout = timeoutMs ?? this.defaultTimeoutMs;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeout);

    try {
      const response = await this.fetchFn(url, {
        signal: controller.signal,
      });

      if (!response.ok) {
        if (response.status === 429) {
          const retryHeader = response.headers.get('Retry-After');
          const retrySec = retryHeader ? parseInt(retryHeader, 10) : undefined;
          throw new SkyviewRateLimitError(retrySec);
        }
        const text = await response.text().catch(() => '');
        throw new SkyviewRequestError(
          `SkyView responded with status ${response.status}`,
          response.status,
          text
        );
      }

      return response;
    } catch (err: unknown) {
      if ((err as Error)?.name === 'AbortError') {
        throw new SkyviewTimeoutError(timeout);
      }
      if (err instanceof SkyviewError) {
        throw err;
      }
      throw new SkyviewRequestError((err as Error).message ?? 'Network error', 0);
    } finally {
      clearTimeout(timer);
    }
  }
}
